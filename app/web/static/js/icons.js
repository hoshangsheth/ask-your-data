/** SVG markup for an icon name (empty string if unknown). */
export function icon(name) {
  const p = PATHS[name];
  if (!p) return "";
  // Default 16px; CSS can override per context.
  return `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${p}</svg>`;
}

/** Replace every empty [data-icon] placeholder under `root` with its SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    if (!el.firstElementChild) el.innerHTML = icon(el.dataset.icon);
  });
}
